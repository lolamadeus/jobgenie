"""Job Search Hub: a read-only local web view of the Markdown knowledge base.

Run from the repo root:  uv run hub/server.py [--port 8787]
Files are re-read on every request, so there is no build step and no cache to clear.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import mimetypes
import re
import sys
import webbrowser
from datetime import date, datetime
from http import HTTPStatus
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from pathlib import Path
from urllib.parse import unquote, urlparse

import markdown
import yaml

ROOT = Path(__file__).resolve().parent.parent
STATIC = Path(__file__).resolve().parent / "static"

# Folders whose changes should refresh the page.
WATCHED = ["knowledge", "pipeline", "documents", "log", "inbox", "sources", "hub/static"]
# Folders whose raw files may be downloaded through /files/.
DOWNLOADABLE = ["documents", "inbox"]
# Portfolio library (optional, see library/README.md). Off until library/config.yaml says enabled: true.
LIBRARY = ROOT / "library"
LIB_APP = LIBRARY / "app"
LIB_DATA = LIBRARY / "library.json"     # generated by library/tools/build.py
LIB_CONFIG = LIBRARY / "config.yaml"    # agents edit this during setup
MARKS = LIBRARY / "marks.json"          # the user's labels from the library app (rating, fav, use, hide, note)
ANSWERS = LIBRARY / "answers.json"      # the user's answers to library questions, for agents to process
LIBRARY_WATCHED = ["library/library.json", "library/config.yaml"]
RATINGS = {"great", "good", "mid", "bad", None}
_media_index: dict = {"mtime": None, "paths": {}}
_store_lock = __import__("threading").Lock()


def read_json(path: Path, default):
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return default


def write_json_atomic(path: Path, data):
    tmp = path.with_suffix(path.suffix + ".tmp")
    tmp.write_text(json.dumps(data, ensure_ascii=False, indent=1), encoding="utf-8")
    tmp.replace(path)


def library_config() -> dict:
    try:
        cfg = yaml.safe_load(LIB_CONFIG.read_text(encoding="utf-8")) or {}
    except (OSError, yaml.YAMLError):
        cfg = {}
    uses = [str(u).strip().lower() for u in (cfg.get("uses") or ["portfolio", "cv"]) if str(u).strip()]
    return {"enabled": bool(cfg.get("enabled")), "title": cfg.get("title") or "Portfolio library",
            "uses": uses[:6], "roots": cfg.get("roots") or []}


def apply_mark(body: dict) -> dict:
    """One label change from the library app. Item ids are 12-hex library ids or 'p:<project-slug>'."""
    mid = str(body.get("id", ""))
    if not re.fullmatch(r"[0-9a-f]{12}|p:[a-z0-9-]{1,60}", mid):
        raise ValueError("bad id")
    field, value = body.get("field"), body.get("value")
    with _store_lock:
        marks = read_json(MARKS, {})
        m = marks.get(mid, {})
        if field == "rating":
            if value not in RATINGS:
                raise ValueError("bad rating")
            m["rating"] = value
        elif field in ("fav", "hide"):
            m[field] = bool(value)
        elif field == "use":
            if not isinstance(value, list) or not set(value) <= set(library_config()["uses"]):
                raise ValueError("bad use")
            m["use"] = sorted(set(value))
        elif field == "note":
            m["note"] = str(value or "")[:2000]
        else:
            raise ValueError("bad field")
        m = {k: v for k, v in m.items() if k != "at" and v not in (None, False, "", [])}
        if m:
            m["at"] = datetime.now().isoformat(timespec="seconds")
            marks[mid] = m
        else:
            marks.pop(mid, None)
        write_json_atomic(MARKS, marks)
    return m


def add_answer(body: dict) -> dict:
    text = str(body.get("text", "")).strip()[:4000]
    if not text:
        raise ValueError("empty answer")
    entry = {"q": str(body.get("q", ""))[:600], "ref": str(body.get("ref", ""))[:200], "text": text,
             "at": datetime.now().isoformat(timespec="seconds"), "status": "new"}
    with _store_lock:
        answers = read_json(ANSWERS, [])
        answers.append(entry)
        write_json_atomic(ANSWERS, answers)
    return entry


def media_path(mid: str) -> Path | None:
    """Library files are served by id only (never by a raw path), and only from inside a configured root."""
    if not LIB_DATA.is_file():
        return None
    mt = LIB_DATA.stat().st_mtime_ns
    if _media_index["mtime"] != mt:
        data = json.loads(LIB_DATA.read_text(encoding="utf-8"))
        _media_index["paths"] = {x["id"]: x["path"] for x in data.get("items", [])}
        _media_index["mtime"] = mt
    p = _media_index["paths"].get(mid)
    if not p:
        return None
    path = Path(p).resolve()
    roots = [Path(str(r.get("path") if isinstance(r, dict) else r)).resolve() for r in library_config()["roots"]]
    return path if any(path.is_relative_to(r) for r in roots) else None

FRONTMATTER = re.compile(r"\A---\s*\r?\n(.*?)\r?\n---\s*(?:\r?\n|\Z)", re.S)
MD_EXT = ["tables", "fenced_code", "sane_lists"]


def rel(p: Path) -> str:
    return p.relative_to(ROOT).as_posix()


LIST_ITEM = re.compile(r"^\s*(?:[-*+]|\d+\.)\s")


def fix_lists(body: str) -> str:
    """Python-Markdown needs a blank line before a list; agents often omit it. Insert one."""
    out, prev, in_code = [], "", False
    for line in body.splitlines():
        if line.lstrip().startswith("```"):
            in_code = not in_code
        if (not in_code and LIST_ITEM.match(line) and prev.strip()
                and not LIST_ITEM.match(prev) and not prev.startswith((" ", "\t"))):
            out.append("")
        out.append(line)
        prev = line
    return "\n".join(out)


def load_doc(path: Path) -> dict:
    text = path.read_text(encoding="utf-8")
    meta, body, error = {}, text, None
    m = FRONTMATTER.match(text)
    if m:
        body = text[m.end():]
        try:
            meta = yaml.safe_load(m.group(1)) or {}
            if not isinstance(meta, dict):
                error, meta = "Frontmatter is not a key/value mapping", {}
        except yaml.YAMLError as e:
            error = f"Frontmatter YAML error: {e}"
    return {
        "path": rel(path),
        "meta": meta,
        "html": markdown.markdown(fix_lists(body), extensions=MD_EXT) if body.strip() else "",
        "error": error,
        "mtime": datetime.fromtimestamp(path.stat().st_mtime).isoformat(timespec="seconds"),
    }


def load_one(relpath: str) -> dict | None:
    p = ROOT / relpath
    return load_doc(p) if p.is_file() else None


def load_dir(relpath: str, recursive: bool = False) -> list[dict]:
    d = ROOT / relpath
    if not d.is_dir():
        return []
    files = d.rglob("*.md") if recursive else d.glob("*.md")
    return [load_doc(p) for p in sorted(files)]


def list_files(relpath: str) -> list[dict]:
    """Non-Markdown files (PDF, DOCX...) for download."""
    d = ROOT / relpath
    if not d.is_dir():
        return []
    out = []
    for p in sorted(d.rglob("*")):
        if p.is_file() and p.suffix.lower() != ".md" and not p.name.startswith("."):
            st = p.stat()
            out.append({
                "path": rel(p),
                "name": p.name,
                "size": st.st_size,
                "mtime": datetime.fromtimestamp(st.st_mtime).isoformat(timespec="seconds"),
            })
    return out


def collect() -> dict:
    return {
        "generated": datetime.now().isoformat(timespec="seconds"),
        "profile": load_one("knowledge/profile.md"),
        "preferences": load_one("knowledge/preferences.md"),
        "skills": load_one("knowledge/skills.md"),
        "education": load_one("knowledge/education.md"),
        "achievements": load_one("knowledge/achievements.md"),
        "questions": load_one("knowledge/open-questions.md"),
        "strategy": load_one("knowledge/strategy.md"),
        "cvguide": load_one("knowledge/cv-guide.md"),
        "leads": load_dir("pipeline/leads"),
        "experience": load_dir("knowledge/experience"),
        "applications": load_dir("pipeline/applications"),
        "companies": load_dir("pipeline/companies"),
        "contacts": load_dir("pipeline/contacts"),
        "documents": load_dir("documents", recursive=True),
        "files": list_files("documents"),
        "inbox": list_files("inbox") + [
            {"path": d["path"], "name": Path(d["path"]).name} for d in load_dir("inbox")
        ],
        "logs": list(reversed(load_dir("log"))),
        "sources": load_dir("sources", recursive=True),  # raw material, viewable via links only
        "library": {k: v for k, v in library_config().items() if k in ("enabled", "title")},
    }


def version(folders: list[str]) -> str:
    h = hashlib.sha1()
    for folder in folders:
        d = ROOT / folder
        if not d.is_dir():
            continue
        for p in sorted(d.rglob("*")):
            if p.is_file():
                st = p.stat()
                h.update(f"{p}|{st.st_mtime_ns}|{st.st_size}".encode())
    return h.hexdigest()[:16]


def file_version(paths: list[str]) -> str:
    h = hashlib.sha1()
    for rp in paths:
        p = ROOT / rp
        if p.is_file():
            st = p.stat()
            h.update(f"{rp}|{st.st_mtime_ns}|{st.st_size}".encode())
    return h.hexdigest()[:16]


def json_default(o):
    if isinstance(o, (date, datetime)):
        return o.isoformat()
    return str(o)


class Handler(BaseHTTPRequestHandler):
    server_version = "JobSearchHub/1.0"

    def log_message(self, fmt, *args):  # quieter console: only errors
        if not (len(args) > 1 and str(args[1])[:1] in ("2", "3")):
            super().log_message(fmt, *args)

    def send_bytes(self, body: bytes, ctype: str, status=HTTPStatus.OK):
        self.send_response(status)
        self.send_header("Content-Type", ctype)
        self.send_header("Content-Length", str(len(body)))
        self.send_header("Cache-Control", "no-store")
        self.end_headers()
        self.wfile.write(body)

    def send_json(self, obj):
        self.send_bytes(json.dumps(obj, default=json_default).encode(), "application/json")

    def send_file(self, path: Path, download: bool = False):
        ctype = mimetypes.guess_type(path.name)[0] or "application/octet-stream"
        if ctype.startswith("text/") or ctype in ("application/javascript", "application/json"):
            ctype += "; charset=utf-8"
        body = path.read_bytes()
        self.send_response(HTTPStatus.OK)
        self.send_header("Content-Type", ctype)
        self.send_header("Content-Length", str(len(body)))
        self.send_header("Cache-Control", "no-store")
        if download:
            self.send_header("Content-Disposition", f'inline; filename="{path.name}"')
        self.end_headers()
        self.wfile.write(body)

    def not_found(self):
        self.send_bytes(b"Not found", "text/plain", HTTPStatus.NOT_FOUND)

    def do_GET(self):
        url = urlparse(self.path)
        route = unquote(url.path)
        try:
            if route in ("/", "/index.html"):
                return self.send_file(STATIC / "index.html")
            if route == "/api/data":
                return self.send_json(collect())
            if route == "/api/version":
                return self.send_json({
                    "data": version([f for f in WATCHED if f != "hub/static"]),
                    "static": version(["hub/static", "library/app"]),
                    "library": file_version(LIBRARY_WATCHED),
                })
            if route in ("/library", "/library/"):
                return self.send_file(LIB_APP / "index.html")
            if route.startswith("/library/app/"):
                return self.serve_under(LIB_APP, route[len("/library/app/"):])
            if route == "/api/library/marks":
                return self.send_json({"marks": read_json(MARKS, {}), "answers": read_json(ANSWERS, []),
                                       "config": library_config()})
            if route == "/api/library":
                if not LIB_DATA.is_file():
                    return self.send_json({"missing": True, "config": library_config()})
                return self.send_bytes(LIB_DATA.read_bytes(), "application/json")
            if route.startswith("/thumbs/"):
                return self.serve_under(LIBRARY / "thumbs", route[len("/thumbs/"):])
            if route.startswith("/media/"):
                p = media_path(route[len("/media/"):])
                if not p or not p.is_file():
                    return self.not_found()
                return self.send_range(p)
            if route.startswith("/static/"):
                return self.serve_under(STATIC, route[len("/static/"):])
            if route.startswith("/files/"):
                relpath = route[len("/files/"):]
                if relpath.split("/", 1)[0] in DOWNLOADABLE:
                    return self.serve_under(ROOT, relpath, download=True)
            return self.not_found()
        except Exception as e:  # keep the server alive on a bad file
            msg = f"Hub error: {type(e).__name__}: {e}".encode()
            self.send_bytes(msg, "text/plain", HTTPStatus.INTERNAL_SERVER_ERROR)

    def do_POST(self):
        # Two kinds of write: the library app's labels and answers (the user's own data), and
        # /api/open, which opens a link in the user's default browser so links clicked in the
        # Claude app's browser pane don't navigate the Hub away. The custom header can't be sent
        # cross-origin without a CORS preflight (never granted), so only the Hub's own pages can
        # call these.
        route = urlparse(self.path).path
        if route in ("/api/library/mark", "/api/library/answer") and self.headers.get("X-Hub") == "library":
            try:
                length = min(int(self.headers.get("Content-Length") or 0), 16384)
                body = json.loads(self.rfile.read(length) or b"{}")
                out = apply_mark(body) if route.endswith("mark") else add_answer(body)
                return self.send_json({"ok": True, "saved": out})
            except (ValueError, TypeError) as e:
                return self.send_bytes(f"Bad request: {e}".encode(), "text/plain", HTTPStatus.BAD_REQUEST)
        if route != "/api/open" or self.headers.get("X-Hub") != "open":
            return self.not_found()
        try:
            length = min(int(self.headers.get("Content-Length") or 0), 8192)
            link = str(json.loads(self.rfile.read(length) or b"{}").get("url", ""))
            parts = urlparse(link)
            if parts.scheme not in ("http", "https") or not parts.netloc or re.search(r"[\s\x00-\x1f]", link):
                return self.send_bytes(b"Bad link", "text/plain", HTTPStatus.BAD_REQUEST)
            webbrowser.open(link, new=2)
            return self.send_json({"opened": True})
        except Exception as e:
            msg = f"Hub error: {type(e).__name__}: {e}".encode()
            return self.send_bytes(msg, "text/plain", HTTPStatus.INTERNAL_SERVER_ERROR)

    def send_range(self, path: Path):
        """Stream a media file with HTTP Range support, so audio/video can seek."""
        size = path.stat().st_size
        ctype = mimetypes.guess_type(path.name)[0] or "application/octet-stream"
        if path.suffix.lower() in (".mkv",):
            ctype = "video/webm"  # lets Chromium try it; many MKVs are H.264 and play
        start, end = 0, size - 1
        rng = self.headers.get("Range")
        m = re.match(r"bytes=(\d*)-(\d*)", rng or "")
        if m:
            if m.group(1):
                start = int(m.group(1))
                end = int(m.group(2)) if m.group(2) else size - 1
            elif m.group(2):
                start = max(0, size - int(m.group(2)))
            end = min(end, size - 1)
        length = end - start + 1
        self.send_response(HTTPStatus.PARTIAL_CONTENT if m else HTTPStatus.OK)
        self.send_header("Content-Type", ctype)
        self.send_header("Accept-Ranges", "bytes")
        self.send_header("Content-Length", str(length))
        if m:
            self.send_header("Content-Range", f"bytes {start}-{end}/{size}")
        self.end_headers()
        try:
            with open(path, "rb") as fh:
                fh.seek(start)
                left = length
                while left > 0:
                    chunk = fh.read(min(512 * 1024, left))
                    if not chunk:
                        break
                    self.wfile.write(chunk)
                    left -= len(chunk)
        except (ConnectionResetError, BrokenPipeError, ConnectionAbortedError):
            pass  # the browser stops reading when it seeks; that's fine

    def serve_under(self, base: Path, relpath: str, download: bool = False):
        target = (base / relpath).resolve()
        if not target.is_relative_to(base.resolve()) or not target.is_file():
            return self.not_found()
        return self.send_file(target, download)


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--port", type=int, default=8787)
    args = ap.parse_args()
    srv = ThreadingHTTPServer(("127.0.0.1", args.port), Handler)
    print(f"Job Search Hub on http://127.0.0.1:{args.port}  (root: {ROOT})", flush=True)
    try:
        srv.serve_forever()
    except KeyboardInterrupt:
        pass


if __name__ == "__main__":
    sys.exit(main())
