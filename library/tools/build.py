"""Merge the scan with the curated files into library/library.json (what the library app reads).

    uv run library/tools/build.py

Inputs
  scan/items.json, scan/folders.json, scan/meta.json   generated by scan.py
  thumbs/<id>.jpg                                      generated by thumbs.py
  projects.yaml    curated: one entry per project (client job, game, campaign, case study...),
                   and which scanned folders belong to it
  curation.yaml    curated: per-item overrides (title, project, tags, hide), folder notes, rules
  questions.yaml   curated: extra questions for the user, shown in the app's Questions tab
Never hand-edit library.json: edit the curated files and rebuild.
"""
from __future__ import annotations

import json
import re
from datetime import datetime
from pathlib import Path

import yaml

LIB = Path(__file__).resolve().parents[1]
SCAN = LIB / "scan"
DEFAULT_TIERS = [{"key": "headline", "label": "Headline work"}, {"key": "notable", "label": "Notable"},
                 {"key": "other", "label": "Other work"}, {"key": "personal", "label": "Personal projects"},
                 {"key": "not-credit", "label": "Tests, pitches and reference (not credits)"}]


def load_yaml(name: str, default):
    p = LIB / name
    if not p.is_file():
        return default
    return yaml.safe_load(p.read_text(encoding="utf-8")) or default


def pretty(name: str) -> str:
    s = re.sub(r"\.[a-z0-9]{2,5}$", "", name, flags=re.I)
    return re.sub(r"\s+", " ", re.sub(r"[_]+", " ", s)).strip()


def main():
    if not (SCAN / "items.json").is_file():
        raise SystemExit("No scan yet: run `uv run library/tools/scan.py` first.")
    items = json.loads((SCAN / "items.json").read_text(encoding="utf-8"))
    folders = json.loads((SCAN / "folders.json").read_text(encoding="utf-8"))
    meta = json.loads((SCAN / "meta.json").read_text(encoding="utf-8"))
    cfg = load_yaml("config.yaml", {})
    pdoc = load_yaml("projects.yaml", {})
    projects = pdoc.get("projects") or []
    tiers = pdoc.get("tiers") or DEFAULT_TIERS
    cur = load_yaml("curation.yaml", {})
    cur_items, cur_folders = cur.get("items") or {}, cur.get("folders") or {}
    # rules: [{match: regex on the file name, path: regex on the path inside its root, project:, kind:, tags:, hide: true}]
    # The first matching rule applies, and only where the item has no explicit entry in `items`.
    rules = [(re.compile(r["match"], re.I) if r.get("match") else None, re.compile(r["path"], re.I) if r.get("path") else None, r)
             for r in (cur.get("rules") or [])]

    def rule_for(name: str, rel: str) -> dict:
        for rx, px, r in rules:
            if (rx or px) and (rx is None or rx.search(name)) and (px is None or px.search(rel)):
                return r
        return {}

    # folder -> project: projects.yaml `folders` entries are a folder name (matched in any root),
    # "ROOT|name" for one root, or "ROOT|*" for everything under a root
    folder_project = {}
    for p in projects:
        for spec in p.get("folders") or []:
            spec_l = str(spec).lower()
            for f in folders:
                key = f"{f['root']}|{f['project']}".lower()
                if spec_l in (key, f["project"].lower()) or (spec_l.endswith("|*") and spec_l[:-2] == f["root"].lower()):
                    folder_project[f["id"]] = p["slug"]
    for f in folders:
        note = cur_folders.get(f"{f['root']}|{f['project']}") or cur_folders.get(f["project"]) or {}
        if note.get("project"):
            folder_project[f["id"]] = note["project"]
        f["project_slug"] = folder_project.get(f["id"])
        f["note"] = note.get("note", "")
        f["ignore"] = bool(note.get("ignore"))
    folder_by_id = {f["id"]: f for f in folders}

    out_items = []
    for r in items:
        c = cur_items.get(r["id"]) or {}
        auto = {} if c else rule_for(r["name"], r["rel"])
        f = folder_by_id.get(r["folder"], {})
        if c.get("hide") or auto.get("hide") or f.get("ignore"):
            continue
        thumb = (LIB / "thumbs" / f"{r['id']}.jpg").is_file()
        out_items.append({
            "id": r["id"], "path": r["path"], "name": r["name"], "rel": r["rel"], "root": r["root"], "ext": r["ext"],
            "kind": c.get("kind") or auto.get("kind") or r["kind"],
            "folder": f.get("project", ""), "folder_id": r["folder"],
            "project": c.get("project") or auto.get("project") or f.get("project_slug"),
            "title": c.get("title") or r.get("title_tag") or "", "label": c.get("title") or r.get("title_tag") or pretty(r["name"]),
            "desc": c.get("desc", ""), "tags": c.get("tags") or auto.get("tags") or [],
            "mtime": r["mtime"], "size": r["size"], "duration": r.get("duration"),
            "width": r.get("width"), "height": r.get("height"),
            "thumb": ("strip" if r["kind"] == "video" else "single") if thumb else None,
            "reviewed": bool(c), "error": r.get("probe_error"),
        })

    for p in projects:
        mine = [i for i in out_items if i["project"] == p["slug"]]
        p["count"] = len(mine)
        p["by_kind"] = {k: sum(1 for i in mine if i["kind"] == k) for k in sorted({i["kind"] for i in mine})}
        dates = [i["mtime"] for i in mine]
        p["first"], p["last"] = (min(dates), max(dates)) if dates else (None, None)
        p.setdefault("tier", "other")

    kinds = sorted({i["kind"] for i in out_items}, key=lambda k: (["image", "video", "audio", "document", "model"] + [k]).index(k))
    unmapped = [f for f in folders if not f.get("project_slug") and not f.get("ignore") and f["files"]]
    out = {
        "built": datetime.now().isoformat(timespec="seconds"), "scanned": meta.get("scanned"),
        "title": cfg.get("title") or "Portfolio library", "kinds": kinds, "tiers": tiers,
        "counts": {"items": len(out_items), "projects": len(projects), "folders": len(folders),
                   "unmapped_folders": len(unmapped), **{k: sum(1 for i in out_items if i["kind"] == k) for k in kinds}},
        "projects": projects, "items": out_items,
        "folders": [{k: f.get(k) for k in ("id", "root", "root_label", "project", "path", "files", "counts", "first", "last",
                                            "examples", "project_slug", "note", "ignore")} for f in folders],
        "questions": load_yaml("questions.yaml", {}).get("questions") or [],
    }
    (LIB / "library.json").write_text(json.dumps(out, ensure_ascii=False, default=str), encoding="utf-8")
    print(json.dumps(out["counts"]))


if __name__ == "__main__":
    main()
